/* ── The width query (§3) ─────────────────────────────────────────── */

bool sutr_sueas_get_width_entry_ex(uint32_t codepoint,
                                   sueas_width_entry_t *out_entry,
                                   sueas_status_code_t *out_error)
{
    sueas_width_entry_t e;
    sueas_spacing_t sp;
    sueas_eaw_t eaw;
    uint16_t flags = 0u;

    if (out_error != NULL)
        *out_error = SUEAS_OK;
    if (out_entry == NULL)
        return sueas_fail(out_error, SUEAS_ERR_NULL_ARGUMENT);
    if (!sutr_sueas_is_renderable(codepoint))
        return sueas_fail(out_error, SUEAS_ERR_ILLEGAL_ZONE);

    sp = sutr_sueas_spacing_of(codepoint);
    eaw = sutr_sueas_eaw_of(codepoint);

    switch (sp) {
    case SUEAS_SPACING_WIDE:        flags |= SUEAS_FLAG_WIDE;         break;
    case SUEAS_SPACING_NARROW:      flags |= SUEAS_FLAG_NARROW;       break;
    case SUEAS_SPACING_CONDITIONAL: flags |= SUEAS_FLAG_CONDITIONAL;  break;
    default: break;
    }
    (void)eaw;

    /* Proportional micro-spacing is granted to non-East-Asian Narrow text and
     * to Ambiguous punctuation; grid snap is forced for the East Asian grid;
     * punctuation centering is granted to fullwidth and halfwidth marks. */
    if (sp == SUEAS_SPACING_NARROW)
        flags |= SUEAS_FLAG_PROPORTIONAL;
    if (sp == SUEAS_SPACING_WIDE)
        flags |= SUEAS_FLAG_GRID_SNAP | SUEAS_FLAG_EAST_ASIAN;
    if (sutr_sueas_is_east_asian(codepoint))
        flags |= SUEAS_FLAG_EAST_ASIAN;
    if (eaw == SUEAS_EAW_FULLWIDTH || eaw == SUEAS_EAW_HALFWIDTH)
        flags |= SUEAS_FLAG_PUNCT_ADJUST | SUEAS_FLAG_GRID_SNAP;
    if (sutr_sueas_is_neography(codepoint))
        flags |= SUEAS_FLAG_NATIVE | SUEAS_FLAG_GRID_SNAP;

    /* A space (General_Category Zs, always EAW Neutral) never auto-spaces and
     * never grid-snaps a neighbour: strip the adjustment bits. */
    if (codepoint == 0x00000020u || codepoint == 0x00003000u)
        flags = (uint16_t)(flags & ~(SUEAS_FLAG_PUNCT_ADJUST));

    e.codepoint = codepoint;
    e.spacing_flags = flags;
    e.width_category = (uint8_t)sutr_sueas_width_category_of(codepoint);
    e.column_units = sutr_sueas_column_units(codepoint);
    *out_entry = e;
    return true;
}

bool sutr_sueas_get_width_entry(uint32_t codepoint,
                                sueas_width_entry_t *out_entry)
{
    return sutr_sueas_get_width_entry_ex(codepoint, out_entry, NULL);
}

/* ── Spacing resolution (§4) ──────────────────────────────────────── */

sueas_spacing_t sutr_sueas_resolve_spacing(uint32_t codepoint,
                                           bool chinese_context,
                                           bool vertical_upright)
{
    sueas_spacing_t sp = sutr_sueas_spacing_of(codepoint);

    if (sp == SUEAS_SPACING_CONDITIONAL)
        return chinese_context ? SUEAS_SPACING_NARROW : SUEAS_SPACING_OTHER;
    /* A Narrow character displayed upright in vertical layout is handled as
     * Other (§4.4). */
    if (vertical_upright && sp == SUEAS_SPACING_NARROW)
        return SUEAS_SPACING_OTHER;
    return sp;
}

bool sutr_sueas_needs_space(sueas_spacing_t left, sueas_spacing_t right)
{
    if (left == SUEAS_SPACING_WIDE && right == SUEAS_SPACING_NARROW)
        return true;
    if (left == SUEAS_SPACING_NARROW && right == SUEAS_SPACING_WIDE)
        return true;
    return false;
}

bool sutr_sueas_spacing_decision(uint32_t left_codepoint,
                                 uint32_t right_codepoint,
                                 bool chinese_context,
                                 bool vertical_upright,
                                 sueas_spacing_decision_t *out_decision)
{
    sueas_spacing_decision_t d;
    sueas_spacing_t l;
    sueas_spacing_t r;

    if (out_decision == NULL)
        return false;
    if (!sutr_sueas_is_renderable(left_codepoint) ||
        !sutr_sueas_is_renderable(right_codepoint))
        return false;

    l = sutr_sueas_resolve_spacing(left_codepoint, chinese_context,
                                   vertical_upright);
    r = sutr_sueas_resolve_spacing(right_codepoint, chinese_context,
                                   vertical_upright);

    d.space = sutr_sueas_needs_space(l, r) ? 1u : 0u;
    d.tight = (uint8_t)(d.space ? 0u : 1u);
    d.reserved = 0u;
    d.reserved2 = 0u;
    *out_decision = d;
    return true;
}

/* ── The zero-allocation grid engine (§5) ─────────────────────────── */

size_t sutr_sueas_measure_columns_ex(const uint32_t *stream, size_t length,
                                     bool chinese_context,
                                     bool vertical_upright,
                                     uint16_t *out_columns, size_t capacity)
{
    size_t i;
    size_t total = 0u;

    if (stream == NULL)
        return 0u;

    for (i = 0u; i < length; i++) {
        uint32_t cp = stream[i];
        uint16_t units;

        if (!sutr_sueas_is_renderable(cp)) {
            /* A non-renderable control contributes zero columns and is not
             * written; a consumer that wants a cell marker substitutes its
             * own replacement before measuring. */
            if (out_columns != NULL && i < capacity)
                out_columns[i] = 0u;
            continue;
        }
        /* Column span follows the resolved category: a Conditional character
         * that resolves to Narrow takes one column; an upright Narrow
         * character in vertical layout takes one column. */
        {
            sueas_width_category_t cat = sutr_sueas_width_category_of(cp);
            units = sutr_sueas_column_units(cp);
            if (cat == SUEAS_WIDTH_AMB)
                units = 2u; /* default East Asian context */
            if (sutr_sueas_resolve_spacing(cp, chinese_context,
                                           vertical_upright)
                    == SUEAS_SPACING_NARROW)
                units = 1u;
        }
        if (out_columns != NULL && i < capacity)
            out_columns[i] = units;
        total += units;
    }
    return total;
}

size_t sutr_sueas_measure_columns(const uint32_t *stream, size_t length,
                                  uint16_t *out_columns, size_t capacity)
{
    return sutr_sueas_measure_columns_ex(stream, length, false, false,
                                         out_columns, capacity);
}

size_t sutr_sueas_count_spaces(const uint32_t *stream, size_t length,
                               bool chinese_context, bool vertical_upright)
{
    size_t i;
    size_t count = 0u;
    bool have_prev = false;
    sueas_spacing_t prev = SUEAS_SPACING_OTHER;

    if (stream == NULL)
        return 0u;

    for (i = 0u; i < length; i++) {
        uint32_t cp = stream[i];
        sueas_spacing_t sp;

        if (!sutr_sueas_is_renderable(cp))
            continue;
        sp = sutr_sueas_resolve_spacing(cp, chinese_context, vertical_upright);
        if (have_prev && sutr_sueas_needs_space(prev, sp))
            count++;
        prev = sp;
        have_prev = true;
    }
    return count;
}

