/* SUTS-009 - SuperUnicode Link Detection and Formatting (SULDF)
 *
 * Reference implementation of docs/suts/SUTS-009-suldf.md.
 *
 * Freestanding C99, zero allocation. Every link property of a codepoint is
 * answered by a bounded binary search over one of three static, sorted,
 * non-overlapping range tables compiled from the Unicode 18.0.0
 * linkification data. The scanner walks a codepoint stream exactly once with
 * one fixed 125-entry bracket stack, and the minimal escaper is a second
 * linear pass that owns no state beyond that stack. No path allocates, grows a
 * table, or calls into libc.
 *
 * UTS #58 is the model, not the target: UTS #58 publishes three text files and
 * an algorithm for user-space linkifiers; SULDF compiles the same evidence
 * into immutable binary tables a kernel-hosted text subsystem can consult in
 * O(1) per codepoint.
 */

