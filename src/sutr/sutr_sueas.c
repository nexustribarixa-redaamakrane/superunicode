/* ── Portable byte extraction ─────────────────────────────────────── */

static uint8_t sueas_byte_at(uint32_t cp, unsigned i)
{
    return (uint8_t)((cp >> (8u * i)) & 0xFFu);
}

/* Record the first defect and report failure. A NULL `out_error` is allowed. */
static bool sueas_fail(sueas_status_code_t *out_error, sueas_status_code_t code)
{
    if (out_error != NULL)
        *out_error = code;
    return false;
}

/* ── Zone dispatch (§2.1) ─────────────────────────────────────────── */

sueas_zone_t sutr_sueas_zone_of(uint32_t codepoint)
{
    if (codepoint > SUEAS_LIMIT_SENTINEL)
        return SUEAS_ZONE_EXTSUCS;
    if (codepoint <= SUEAS_LIMIT_UNICODE_MAX)
        return SUEAS_ZONE_BRIDGE;
    if (codepoint >= SUEAS_LIMIT_SCP_MIN && codepoint <= SUEAS_LIMIT_SCP_MAX)
        return SUEAS_ZONE_SCP;
    if (codepoint >= SUEAS_LIMIT_TRAP_MIN && codepoint <= SUEAS_LIMIT_TRAP_MAX)
        return SUEAS_ZONE_TRAP;
    if (codepoint == SUEAS_LIMIT_SENTINEL)
        return SUEAS_ZONE_SENTINEL;
    if (codepoint >= SUEAS_RNUR_MIN && codepoint <= SUEAS_RNUR_MAX)
        return SUEAS_ZONE_RNUR;
    return SUEAS_ZONE_NATIVE;
}

bool sutr_sueas_is_renderable(uint32_t codepoint)
{
    sueas_zone_t z = sutr_sueas_zone_of(codepoint);

    return z == SUEAS_ZONE_BRIDGE || z == SUEAS_ZONE_RNUR ||
           z == SUEAS_ZONE_NATIVE;
}

bool sutr_sueas_is_text_space(uint32_t codepoint)
{
    return sutr_sueas_is_renderable(codepoint);
}

bool sutr_sueas_is_neography(uint32_t codepoint)
{
    return sutr_sueas_zone_of(codepoint) == SUEAS_ZONE_RNUR;
}

bool sutr_sueas_neography_set(uint32_t codepoint, uint32_t *out_set)
{
    if (out_set == NULL)
        return false;
    if (!sutr_sueas_is_neography(codepoint))
        return false;
    *out_set = (codepoint - SUEAS_RNUR_MIN) >> SUEAS_RNUR_SET_SHIFT;
    return true;
}

/* ── FNV-1a primitive (§3.5) ──────────────────────────────────────── */

uint32_t sutr_sueas_hash_codepoint(uint32_t codepoint)
{
    uint32_t h = SUEAS_FNV_OFFSET_BASIS;
    unsigned i;

    for (i = 0u; i < 4u; i++) {
        h ^= (uint32_t)sueas_byte_at(codepoint, i);
        h *= SUEAS_FNV_PRIME;
    }
    return h;
}

/* ── Bounded range search (§3.5) ──────────────────────────────────── */

/* The last range whose `first` is <= cp, or -1 when cp precedes the first
 * range. A standard upper-bound binary search over a sorted, non-overlapping
 * table; O(log R). */
static long sueas_upper_bound(const void *table, uint32_t rows,
                              uint32_t row_bytes, uint32_t cp)
{
    const unsigned char *base = (const unsigned char *)table;
    long lo = 0;
    long hi = (long)rows - 1;
    long found = -1;

    while (lo <= hi) {
        long mid = lo + (hi - lo) / 2;
        uint32_t first;
        const unsigned char *row = base + (size_t)mid * row_bytes;

        /* first is the leading uint32_t of every row layout (§3.1) */
        first = (uint32_t)row[0] | ((uint32_t)row[1] << 8) |
                ((uint32_t)row[2] << 16) | ((uint32_t)row[3] << 24);
        if (first <= cp) {
            found = mid;
            lo = mid + 1;
        } else {
            hi = mid - 1;
        }
    }
    return found;
}

static uint32_t sueas_range_last(const unsigned char *row)
{
    return (uint32_t)row[4] | ((uint32_t)row[5] << 8) |
           ((uint32_t)row[6] << 16) | ((uint32_t)row[7] << 24);
}

static uint32_t sueas_range_value(const unsigned char *row)
{
    return (uint32_t)row[8] | ((uint32_t)row[9] << 8) |
           ((uint32_t)row[10] << 16) | ((uint32_t)row[11] << 24);
}

/* ── Property lookups (§3) ────────────────────────────────────────── */

sueas_spacing_t sutr_sueas_spacing_of(uint32_t codepoint)
{
    long idx;

    if (!sutr_sueas_is_renderable(codepoint))
        return SUEAS_SPACING_OTHER;
    idx = sueas_upper_bound(sueas_spacing_ranges, SUEAS_SPACING_ROWS,
                            sizeof(sueas_spacing_range_t), codepoint);
    if (idx < 0)
        return SUEAS_SPACING_OTHER;
    {
        const unsigned char *row =
            (const unsigned char *)sueas_spacing_ranges +
            (size_t)idx * sizeof(sueas_spacing_range_t);
        if (codepoint <= sueas_range_last(row))
            return (sueas_spacing_t)sueas_range_value(row);
    }
    return SUEAS_SPACING_OTHER;
}

sueas_eaw_t sutr_sueas_eaw_of(uint32_t codepoint)
{
    long idx;

    if (!sutr_sueas_is_renderable(codepoint))
        return SUEAS_EAW_NEUTRAL;
    idx = sueas_upper_bound(sueas_eaw_ranges, SUEAS_EAW_ROWS,
                            sizeof(sueas_eaw_range_t), codepoint);
    if (idx < 0)
        return SUEAS_EAW_NEUTRAL;
    {
        const unsigned char *row =
            (const unsigned char *)sueas_eaw_ranges +
            (size_t)idx * sizeof(sueas_eaw_range_t);
        if (codepoint <= sueas_range_last(row))
            return (sueas_eaw_t)sueas_range_value(row);
    }
    return SUEAS_EAW_NEUTRAL;
}

/* ── The mapped width category (§3.2) ─────────────────────────────── */

/* The sketch's width category is a projection of the two compiled properties:
 *   - Wide (W) East_Asian_Spacing        -> WID  (two columns, East Asian)
 *   - Narrow (N) East_Asian_Spacing      -> NAR  (one column, starter)
 *   - Fullwidth EAW                      -> FULL
 *   - Halfwidth EAW                      -> HALF
 *   - Ambiguous EAW, not Wide spacing    -> AMB  (context-dependent)
 *   - otherwise                          -> NEUTRAL
 * The East_Asian_Spacing value wins for a Wide/Narrow character, because that
 * is the value the spacing algorithm acts on. */
sueas_width_category_t sutr_sueas_width_category_of(uint32_t codepoint)
{
    sueas_spacing_t sp;
    sueas_eaw_t eaw;

    if (!sutr_sueas_is_renderable(codepoint))
        return SUEAS_WIDTH_NEUTRAL;

    sp = sutr_sueas_spacing_of(codepoint);
    eaw = sutr_sueas_eaw_of(codepoint);

    if (sp == SUEAS_SPACING_WIDE)
        return SUEAS_WIDTH_WID;
    if (sp == SUEAS_SPACING_NARROW)
        return SUEAS_WIDTH_NAR;
    if (eaw == SUEAS_EAW_FULLWIDTH)
        return SUEAS_WIDTH_FULL;
    if (eaw == SUEAS_EAW_HALFWIDTH)
        return SUEAS_WIDTH_HALF;
    if (eaw == SUEAS_EAW_AMBIGUOUS)
        return SUEAS_WIDTH_AMB;
    return SUEAS_WIDTH_NEUTRAL;
}

/* ── Grid column span (§3.4) ──────────────────────────────────────── */

/* Two columns for Wide, Fullwidth, and Ambiguous (the latter because the
 * default East Asian context is two columns; a consumer that resolves
 * Ambiguous to one column does so through its own policy). One column for
 * everything else. */
uint8_t sutr_sueas_column_units(uint32_t codepoint)
{
    sueas_width_category_t cat;

    if (!sutr_sueas_is_renderable(codepoint))
        return 0u;
    cat = sutr_sueas_width_category_of(codepoint);
    if (cat == SUEAS_WIDTH_WID || cat == SUEAS_WIDTH_FULL ||
        cat == SUEAS_WIDTH_AMB)
        return 2u;
    return 1u;
}

/* ── Classification predicates (§3) ───────────────────────────────── */

bool sutr_sueas_is_registered(uint32_t codepoint)
{
    long idx;
    const unsigned char *row;

    if (!sutr_sueas_is_renderable(codepoint))
        return false;

    idx = sueas_upper_bound(sueas_spacing_ranges, SUEAS_SPACING_ROWS,
                            sizeof(sueas_spacing_range_t), codepoint);
    if (idx >= 0) {
        row = (const unsigned char *)sueas_spacing_ranges +
              (size_t)idx * sizeof(sueas_spacing_range_t);
        if (codepoint <= sueas_range_last(row))
            return true;
    }
    idx = sueas_upper_bound(sueas_eaw_ranges, SUEAS_EAW_ROWS,
                            sizeof(sueas_eaw_range_t), codepoint);
    if (idx >= 0) {
        row = (const unsigned char *)sueas_eaw_ranges +
              (size_t)idx * sizeof(sueas_eaw_range_t);
        if (codepoint <= sueas_range_last(row))
            return true;
    }
    return false;
}

