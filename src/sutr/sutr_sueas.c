/* SUTR-013 — SuperUnicode East Asian Spacing (SUEAS)
 *
 * Reference implementation of docs/sutr/SUTR-013-sueas.md.
 *
 * Freestanding C99, zero allocation. The East_Asian_Spacing and
 * East_Asian_Width range tables are static, merged, sorted, non-overlapping,
 * and byte-aligned; every query is a bounded binary search. No part of this
 * file reaches for malloc, stdio, or a libc string routine.
 *
 * The layout surface answers three questions a renderer asks on the hot path:
 *
 *   1. What is the grid width of this codepoint — one or two columns? (§3)
 *   2. Does a visible auto-space belong between these two clusters? (§4)
 *   3. How many columns does this stream occupy, and how many auto-spaces
 *      would it receive? (§5)
 *
 * All three are resolved by direct table indexing in O(log R) or O(n), with
 * no property-file parse and no heap.
 */

