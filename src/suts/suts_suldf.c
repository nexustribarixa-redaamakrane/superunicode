/* Every lookup is a bounded probe: the tables have a compile-time-fixed size,
 * so the search depth is a constant of the build, not a function of the
 * address space. The cost per codepoint is O(1). */

static const suldf_term_row_t* suldf_term_lookup(uint32_t cp)
{
    uint32_t lo = 0u;
    uint32_t hi = SULDF_TERM_COUNT;
    while (lo < hi) {
        const suldf_term_row_t *row;
        uint32_t mid = lo + ((hi - lo) / 2u);
        row = &suldf_term_table[mid];
        if (cp < row->first) {
            hi = mid;
        } else if (cp > row->last) {
            lo = mid + 1u;
        } else {
            return row;
        }
    }
    return NULL;
}

